"""configure, the ros-world plug hooks, the join-at-start chain step and the
launcher against a fake $SNAP, a fake snapctl and a temp $SNAP_COMMON (no snapd,
no root, no ROS).

husarion-snap-common comes from $HSC_DIR, default ../husarion-snap-common (its
devel branch: robot_world.sh). The ros-world content mount is a copy of the
worlds/ dir the rosbot snap's renderer writes.
"""

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
FAKE_BIN = Path(__file__).resolve().parent / "fake_bin"
HSC_DIR = Path(os.environ.get("HSC_DIR", REPO.parent / "husarion-snap-common"))

pytestmark = pytest.mark.skipif(
    not (HSC_DIR / "local-ros" / "robot_world.sh").is_file(),
    reason=f"husarion-snap-common with robot_world.sh not found at {HSC_DIR} (set HSC_DIR)",
)

# Stands in for snap-common's ros.* renderer, which needs a ROS install.
FAKE_CONFIGURE_HOOK_ROS = """#!/bin/bash -e
{
  echo "export ROS_DOMAIN_ID=$(snapctl get ros.domain-id)"
  ns="$(snapctl get ros.namespace)"
  [ -n "$ns" ] && echo "export ROS_NAMESPACE=$ns"
  echo "export FASTRTPS_DEFAULT_PROFILES_FILE=${SNAP_COMMON}/rmw/fastdds/udp.xml"
} > "${SNAP_COMMON}/ros.env"
"""

CHAINED_CONFIG = {
    "driver": {
        "name": "oak",
        "model": "OAK-D-PRO",
        "camera-params": "autogenerated",
        "ffmpeg-params": "default",
        "startup-delay": 0,
        "pointcloud": "false",
        "rectify-rgb": "true",
        "depth": "false",
        "resolution": "720P",
        "fps": 30,
        "imu": "false",
        "ir": "false",
        "ir-intensity": 400,
        "bitrate": 3400000,
    },
    "ros": {"domain-id": 7, "namespace": "rosbot_e4607f", "transport": "shm"},
}


class Snap:
    def __init__(self, root: Path):
        self.root = root
        self.snap = root / "snap"
        self.common = root / "common"
        self.data = root / "data"
        self.common.mkdir(parents=True)
        self.data.mkdir()
        self.db = root / "snapctl.json"
        self.ros2_log = root / "ros2.log"
        self.snapctl_log = root / "snapctl.log"

        usr_bin = self.snap / "usr" / "bin"
        usr_bin.mkdir(parents=True)
        for f in (HSC_DIR / "local-ros").glob("*.sh"):
            shutil.copy2(f, usr_bin)
        for f in (REPO / "snap" / "local").glob("*.sh"):
            shutil.copy2(f, usr_bin)
        shutil.copy2(REPO / "snap" / "local" / "ffmpeg-params-default.yaml", self.data)
        (self.data / "camera-params-autogenerated.yaml").write_text("")
        stub = usr_bin / "configure_hook_ros.sh"
        stub.write_text(FAKE_CONFIGURE_HOOK_ROS)
        stub.chmod(0o755)
        hooks = self.snap / "meta" / "hooks"
        shutil.copytree(REPO / "snap" / "hooks", hooks)
        for h in hooks.iterdir():
            h.chmod(0o755)

        self.db.write_text(json.dumps(CHAINED_CONFIG))
        self.env = {
            "PATH": f"{FAKE_BIN}:{os.environ['PATH']}",
            "HOME": str(root),
            "SNAP": str(self.snap),
            "SNAP_COMMON": str(self.common),
            "SNAP_DATA": str(self.data),
            "SNAP_NAME": "husarion-depthai",
            "FAKE_SNAPCTL_DB": str(self.db),
            "FAKE_SNAPCTL_LOG": str(self.snapctl_log),
            "FAKE_SNAPCTL_ACTIVE": "husarion-depthai.daemon",
            "FAKE_SNAPCTL_CONNECTED": "raw-usb,hardware-observe",
            "FAKE_ROS2_LOG": str(self.ros2_log),
        }

    def mount_ros_world(self, root: Path) -> None:
        owner_common = root / f"rosbot-common-{len(list(root.glob('rosbot-common-*')))}"
        owner_common.mkdir()
        env = dict(self.env, SNAP_COMMON=str(owner_common), HSC_WORLD_TEMPLATES=str(HSC_DIR / "local-ros" / "worlds"))
        script = f'source "{HSC_DIR}/local-ros/utils.sh"; source "{HSC_DIR}/local-ros/robot_world.sh"; render_robot_world'
        subprocess.run(["bash", "-c", script], env=env, check=True)
        shutil.rmtree(self.common / "ros-world", ignore_errors=True)
        shutil.copytree(owner_common / "worlds", self.common / "ros-world")

    def run(self, *argv: str) -> subprocess.CompletedProcess:
        return subprocess.run(list(argv), env=self.env, capture_output=True, text=True)

    def hook(self, name: str) -> subprocess.CompletedProcess:
        return self.run(str(self.snap / "meta" / "hooks" / name))

    def launch(self, *chain: str) -> subprocess.CompletedProcess:
        usr_bin = self.snap / "usr" / "bin"
        steps = chain or ("ros_setup.sh",)
        return self.run(*(str(usr_bin / s) for s in steps), str(usr_bin / "launcher.sh"))

    def ros_env(self) -> str:
        return (self.common / "ros.env").read_text()

    def config(self) -> dict:
        return json.loads(self.db.read_text())


@pytest.fixture
def snap(tmp_path: Path) -> Snap:
    return Snap(tmp_path)


def test_configure_joins_mounted_robot_world(snap: Snap, tmp_path: Path):
    snap.mount_ros_world(tmp_path)
    result = snap.hook("configure")
    assert result.returncode == 0, result.stderr

    env = snap.ros_env()
    assert "export ROS_DOMAIN_ID=0" in env
    assert "export RMW_IMPLEMENTATION=rmw_fastrtps_cpp" in env
    assert "unset ROS_LOCALHOST_ONLY ROS_NAMESPACE" in env
    assert "export HSC_ROBOT_WORLD=1" in env
    profiles = [line for line in env.splitlines() if "FASTRTPS_DEFAULT_PROFILES_FILE=" in line]
    assert profiles == [f"export FASTRTPS_DEFAULT_PROFILES_FILE={snap.common}/ros-world/fastdds.xml"]
    assert "rosbot_e4607f" not in env
    assert snap.config()["ros"]["namespace"] == "rosbot_e4607f"
    assert "restart husarion-depthai.daemon" in snap.snapctl_log.read_text()


def test_configure_without_mount_keeps_ros_keys(snap: Snap):
    result = snap.hook("configure")
    assert result.returncode == 0, result.stderr

    env = snap.ros_env()
    assert "export ROS_NAMESPACE=rosbot_e4607f" in env
    assert "HSC_ROBOT_WORLD" not in env


def test_launcher_in_robot_world_drops_namespace_and_shm_gate(snap: Snap, tmp_path: Path):
    snap.mount_ros_world(tmp_path)
    assert snap.hook("configure").returncode == 0

    result = snap.launch()
    assert result.returncode == 0, result.stderr
    ran = snap.ros2_log.read_text()
    assert "namespace:=" not in ran
    assert "name:=oak" in ran
    assert "ROS_DOMAIN_ID=0" in ran
    assert "ROS_NAMESPACE=\n" in ran
    assert f"FASTRTPS_DEFAULT_PROFILES_FILE={snap.common}/ros-world/fastdds.xml" in ran


def test_launcher_without_robot_world_keeps_namespace_and_shm_gate(snap: Snap):
    assert snap.hook("configure").returncode == 0

    result = snap.launch()
    assert result.returncode == 1
    assert "needs the shared-memory connection" in result.stderr

    config = snap.config()
    config["ros"]["transport"] = "udp"
    snap.db.write_text(json.dumps(config))
    result = snap.launch()
    assert result.returncode == 0, result.stderr
    assert "namespace:=rosbot_e4607f" in snap.ros2_log.read_text()


def test_connect_hook_joins_without_running_configure(snap: Snap, tmp_path: Path):
    snap.mount_ros_world(tmp_path)
    # An invalid driver.* value would make configure exit 1 and undo the connection.
    config = snap.config()
    config["driver"]["fps"] = 999
    snap.db.write_text(json.dumps(config))

    result = snap.hook("connect-plug-ros-world")
    assert result.returncode == 0, result.stderr
    assert "export HSC_ROBOT_WORLD=1" in snap.ros_env()
    assert "restart husarion-depthai.daemon" in snap.snapctl_log.read_text()


def test_disconnect_hook_leaves_while_mount_is_live(snap: Snap, tmp_path: Path):
    snap.mount_ros_world(tmp_path)
    assert snap.hook("configure").returncode == 0

    result = snap.hook("disconnect-plug-ros-world")
    assert result.returncode == 0, result.stderr
    env = snap.ros_env()
    assert "HSC_ROBOT_WORLD" not in env
    assert "export ROS_NAMESPACE=rosbot_e4607f" in env
    assert "restart husarion-depthai.daemon" in snap.snapctl_log.read_text()


def test_disconnect_hook_never_fails(snap: Snap, tmp_path: Path):
    snap.mount_ros_world(tmp_path)
    (snap.snap / "usr" / "bin" / "configure_hook_ros.sh").write_text("#!/bin/bash\nexit 1\n")

    result = snap.hook("disconnect-plug-ros-world")
    assert result.returncode == 0, result.stderr
    assert "ros.* keys are invalid" in result.stderr


def test_daemon_start_joins_a_world_rendered_after_configure(snap: Snap, tmp_path: Path):
    assert snap.hook("configure").returncode == 0
    assert "HSC_ROBOT_WORLD" not in snap.ros_env()

    snap.mount_ros_world(tmp_path)
    result = snap.launch("join_robot_world.sh", "ros_setup.sh")
    assert result.returncode == 0, result.stderr
    ran = snap.ros2_log.read_text()
    assert "namespace:=" not in ran
    assert "ROS_DOMAIN_ID=0" in ran
    assert "export HSC_ROBOT_WORLD=1" in snap.ros_env()


def test_daemon_start_picks_up_a_re_rendered_world(snap: Snap, tmp_path: Path):
    snap.mount_ros_world(tmp_path)
    assert snap.hook("configure").returncode == 0
    (snap.common / "ros-world" / "robot.env").write_text(
        "export ROS_DOMAIN_ID=5\nexport FASTRTPS_DEFAULT_PROFILES_FILE=/stale/fastdds.xml\n"
    )

    result = snap.launch("join_robot_world.sh", "ros_setup.sh")
    assert result.returncode == 0, result.stderr
    ran = snap.ros2_log.read_text()
    assert "ROS_DOMAIN_ID=5" in ran
    assert f"FASTRTPS_DEFAULT_PROFILES_FILE={snap.common}/ros-world/fastdds.xml" in ran


def test_daemon_start_without_mount_keeps_ros_env(snap: Snap):
    assert snap.hook("configure").returncode == 0
    before = snap.ros_env()

    config = snap.config()
    config["ros"]["transport"] = "udp"
    snap.db.write_text(json.dumps(config))
    result = snap.launch("join_robot_world.sh", "ros_setup.sh")
    assert result.returncode == 0, result.stderr
    assert snap.ros_env() == before
    assert "namespace:=rosbot_e4607f" in snap.ros2_log.read_text()
